/* Emoji-only message detection (WhatsApp-style large emoji)           */
/* ------------------------------------------------------------------ */

const EMOJI_GRAPHEME_RE = /[\p{Extended_Pictographic}\p{Regional_Indicator}]/u;
const WHITESPACE_RE = /^\s+$/;

/**
 * Number of emoji in a message that consists only of emoji (whitespace
 * between them is allowed). Returns 0 for mixed or plain-text content.
 */
export function getEmojiOnlyCount(text) {
    const trimmed = (text ?? '').trim();
    if (!trimmed) return 0;

    let graphemes;
    try {
        const segmenter = new Intl.Segmenter(undefined, { granularity: 'grapheme' });
        graphemes = Array.from(segmenter.segment(trimmed), (entry) => entry.segment);
    } catch {
        graphemes = Array.from(trimmed);
    }

    const emoji = graphemes.filter((grapheme) => !WHITESPACE_RE.test(grapheme));
    if (emoji.length === 0) return 0;
    if (!emoji.every((grapheme) => EMOJI_GRAPHEME_RE.test(grapheme))) return 0;

    return emoji.length;
}
