export const EMOJIS = Object.entries(RAW_EMOJIS).flatMap(([category, entries]) =>
    entries.map(([char, name, keywords = '']) => ({
        char,
        name,
        category,
        search: `${name} ${keywords}`.toLowerCase(),
    }))
);

const BY_CATEGORY = EMOJIS.reduce((acc, emoji) => {
    (acc[emoji.category] ||= []).push(emoji);
    return acc;
}, {});

const KNOWN_CHARS = new Set(EMOJIS.map((emoji) => emoji.char));

export function getCategoryEmojis(categoryId) {
    return BY_CATEGORY[categoryId] ?? [];
}

/** Match every search term against name + keywords (e.g. "happy face"). */
export function searchEmojis(query) {
    const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
    if (terms.length === 0) return [];
    return EMOJIS.filter((emoji) => terms.every((term) => emoji.search.includes(term)));
}

