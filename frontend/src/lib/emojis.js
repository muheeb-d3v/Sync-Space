/* Recently used + preferences (localStorage)                          */
/* ------------------------------------------------------------------ */

const RECENTS_KEY = 'syncspace:emoji-recents';
const TONE_KEY = 'syncspace:emoji-skin-tone';
const MAX_RECENTS = 24;

function readStorage(key) {
    try {
        return window.localStorage.getItem(key);
    } catch {
        return null;
    }
}

function writeStorage(key, value) {
    try {
        window.localStorage.setItem(key, value);
    } catch {
        // Storage can be unavailable (private mode / quota); ignore.
    }
}

export function getRecentEmojis() {
    const raw = readStorage(RECENTS_KEY);
    if (!raw) return [];
    try {
        const stored = JSON.parse(raw);
        if (!Array.isArray(stored)) return [];
        return stored.filter((char) => KNOWN_CHARS.has(char)).slice(0, MAX_RECENTS);
    } catch {
        return [];
    }
}

export function pushRecentEmoji(char) {
    if (!KNOWN_CHARS.has(char)) return getRecentEmojis();
    const next = [char, ...getRecentEmojis().filter((item) => item !== char)].slice(
        0,
        MAX_RECENTS
    );
    writeStorage(RECENTS_KEY, JSON.stringify(next));
    return next;
}

export function getSkinTone() {
    const stored = readStorage(TONE_KEY);
    return SKIN_TONES.some((tone) => tone.id === stored) ? stored : 'default';
}

export function setSkinTone(toneId) {
    if (SKIN_TONES.some((tone) => tone.id === toneId)) {
        writeStorage(TONE_KEY, toneId);
    }
}

